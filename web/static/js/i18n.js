const STORAGE_KEY = "focal.lang";
const listeners = new Set();
let current = storedLang() || "zh";

function storedLang() {
  try {
    const value = localStorage.getItem(STORAGE_KEY);
    return value in messages ? value : null;
  } catch {
    return null;
  }
}

export function lang() {
  return current;
}

export function has(key) {
  return key in messages[current] || key in messages.zh;
}

export function t(key, params = {}) {
  const template = messages[current][key] ?? messages.zh[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function setLang(next) {
  if (!(next in messages) || next === current) return;
  current = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // Private windows may refuse storage; the choice then lasts for this visit.
  }
  applyI18n();
  listeners.forEach((listener) => listener(next));
}

export function onLangChange(listener) {
  listeners.add(listener);
}

export function applyI18n(root = document) {
  document.documentElement.lang = current === "zh" ? "zh-CN" : "en";
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-attr]").forEach((node) => {
    for (const pair of node.dataset.i18nAttr.split(";")) {
      const [attribute, key] = pair.split(":").map((part) => part.trim());
      if (attribute && key) node.setAttribute(attribute, t(key));
    }
  });
}
